import type { Evidence, Finding } from './engine.ts';
import { visibleWords } from './html.ts';

export interface Verdict {
  mode: 'Static' | 'SSG' | 'ISR' | 'SSR' | 'CSR' | 'Hybrid' | 'Server-rendered';
  summary: string;
  reasons: string[];
}

const has = (f: Finding[], id: string) => f.some((x) => x.id === id && x.confidence !== 'trace');

export function renderingVerdict(ev: Evidence, findings: Finding[]): Verdict {
  const words = visibleWords(ev.html);
  const reasons: string[] = [`The first HTML response carries ${words.toLocaleString('en-US')} words of visible text.`];
  const h = ev.headers;
  const nextData = /<script id="__NEXT_DATA__"[^>]*>([\s\S]*?)<\/script>/.exec(ev.html)?.[1] ?? '';
  const emptyMount = /<div id="(?:root|app|__next|__nuxt|svelte)"[^>]*>\s*<\/div>/.test(ev.html);

  if (h['x-nextjs-cache'] || h['x-nextjs-prerender']) {
    reasons.push(`Next.js cache header: ${h['x-nextjs-cache'] ? `x-nextjs-cache: ${h['x-nextjs-cache']}` : 'x-nextjs-prerender: 1'}.`);
    const stale = h['x-nextjs-stale-time'] || /s-maxage=\d+.*stale-while-revalidate/.test(h['cache-control'] ?? '');
    return { mode: stale ? 'ISR' : 'SSG', summary: stale ? 'Pre-rendered pages, regenerated in the background (incremental static regeneration).' : 'Pre-rendered at build time and served from cache.', reasons };
  }
  if (nextData) {
    if (/"gssp"\s*:\s*true/.test(nextData)) return { mode: 'SSR', summary: 'Rendered on the server for every request (getServerSideProps).', reasons: [...reasons, '__NEXT_DATA__ declares "gssp": true.'] };
    if (/"nextExport"\s*:\s*true/.test(nextData)) return { mode: 'Static', summary: 'Static export: plain HTML files, no Next.js server.', reasons: [...reasons, '__NEXT_DATA__ declares "nextExport": true.'] };
    if (/"gsp"\s*:\s*true/.test(nextData)) return { mode: 'SSG', summary: 'Pre-rendered at build time (getStaticProps).', reasons: [...reasons, '__NEXT_DATA__ declares "gsp": true.'] };
  }
  if (/self\.__next_f\.push/.test(ev.html)) {
    return { mode: 'Hybrid', summary: 'React Server Components: HTML streams from the server, interactive parts hydrate in the browser.', reasons: [...reasons, 'The page streams an RSC payload (self.__next_f).'] };
  }
  for (const [id, mode, summary] of [
    ['hugo', 'Static', 'Static files generated by Hugo.'], ['jekyll', 'Static', 'Static files generated by Jekyll.'],
    ['eleventy', 'Static', 'Static files generated by Eleventy.'], ['gatsby', 'SSG', 'Pre-rendered by Gatsby, hydrated with React.'],
    ['docusaurus', 'SSG', 'Pre-rendered docs (Docusaurus), hydrated with React.'], ['vitepress', 'SSG', 'Pre-rendered docs (VitePress), hydrated with Vue.'],
    ['astro', 'SSG', 'Astro: HTML first, JavaScript only for interactive islands.'],
    ['wordpress', 'Server-rendered', 'PHP renders each page from the database (often behind a page cache).'],
    ['drupal', 'Server-rendered', 'PHP renders each page from the database.'],
    ['shopify', 'Server-rendered', 'Shopify renders Liquid templates on its servers.'],
    ['rails', 'Server-rendered', 'Rails renders HTML on the server.'], ['django', 'Server-rendered', 'Django renders HTML on the server.'],
    ['laravel', 'Server-rendered', 'Laravel renders HTML on the server.'], ['phoenix', 'Server-rendered', 'Phoenix LiveView renders on the server and patches over a socket.'],
  ] as const) {
    if (has(findings, id)) return { mode, summary, reasons: [...reasons, `${findings.find((f) => f.id === id)!.name} detected.`] };
  }
  if (emptyMount && words < 60) {
    return { mode: 'CSR', summary: 'Client-side rendered: the server sends an empty shell and JavaScript builds the page.', reasons: [...reasons, 'An empty mount node (<div id="root"></div> or similar) waits for JavaScript.'] };
  }
  const hydrates = ['react', 'vue', 'svelte', 'angular', 'solid', 'nuxt', 'sveltekit', 'remix'].some((id) => has(findings, id));
  if (hydrates && words >= 60) return { mode: 'SSR', summary: 'Server- or pre-rendered HTML, hydrated by a JavaScript framework.', reasons };
  if (hydrates) return { mode: 'CSR', summary: 'Mostly built in the browser by a JavaScript framework.', reasons };
  return { mode: 'Static', summary: 'Plain server-delivered HTML with little or no client framework.', reasons };
}

export interface SecurityRow {
  id: string;
  label: string;
  pass: boolean;
  value: string;
  advice: string;
}

export interface Security {
  grade: 'A' | 'B' | 'C' | 'D' | 'F';
  rows: SecurityRow[];
}

export function securityReport(ev: Evidence, startedHttp: boolean): Security {
  const h = ev.headers;
  const csp = h['content-security-policy'] ?? '';
  const hsts = h['strict-transport-security'] ?? '';
  const maxAge = Number(/max-age=(\d+)/i.exec(hsts)?.[1] ?? 0);
  const insecureCookies = ev.setCookies.filter((c) => !/;\s*secure/i.test(c) || !/;\s*samesite=/i.test(c)).map((c) => c.split('=')[0]);
  const rows: SecurityRow[] = [
    { id: 'https', label: 'HTTPS', pass: ev.finalUrl.startsWith('https:'), value: startedHttp && ev.finalUrl.startsWith('https:') ? 'http redirects to https' : new URL(ev.finalUrl).protocol.slice(0, -1), advice: 'Serve everything over HTTPS and redirect plain http.' },
    { id: 'hsts', label: 'Strict-Transport-Security', pass: maxAge >= 15_552_000, value: hsts || 'missing', advice: 'Strict-Transport-Security: max-age=31536000; includeSubDomains' },
    { id: 'csp', label: 'Content-Security-Policy', pass: !!csp && !/script-src[^;]*'unsafe-inline'/.test(csp), value: csp ? short(csp) : 'missing', advice: "Content-Security-Policy: default-src 'self'; script-src 'self'" },
    { id: 'frames', label: 'Clickjacking protection', pass: /deny|sameorigin/i.test(h['x-frame-options'] ?? '') || /frame-ancestors/.test(csp), value: h['x-frame-options'] || (/frame-ancestors[^;]*/.exec(csp)?.[0] ?? 'missing'), advice: "Content-Security-Policy: frame-ancestors 'self'" },
    { id: 'nosniff', label: 'X-Content-Type-Options', pass: /nosniff/i.test(h['x-content-type-options'] ?? ''), value: h['x-content-type-options'] || 'missing', advice: 'X-Content-Type-Options: nosniff' },
    { id: 'referrer', label: 'Referrer-Policy', pass: !!h['referrer-policy'] && !/unsafe-url/.test(h['referrer-policy']), value: h['referrer-policy'] || 'missing', advice: 'Referrer-Policy: strict-origin-when-cross-origin' },
    { id: 'permissions', label: 'Permissions-Policy', pass: !!h['permissions-policy'], value: h['permissions-policy'] ? short(h['permissions-policy']) : 'missing', advice: 'Permissions-Policy: camera=(), microphone=(), geolocation=()' },
    { id: 'cookies', label: 'Cookie flags', pass: insecureCookies.length === 0, value: ev.setCookies.length ? (insecureCookies.length ? `missing Secure/SameSite: ${insecureCookies.slice(0, 4).join(', ')}` : `${ev.setCookies.length} cookie(s), all flagged`) : 'no cookies set', advice: 'Set-Cookie: …; Secure; HttpOnly; SameSite=Lax' },
    { id: 'tls', label: 'Certificate', pass: !!ev.tls && ev.tls.authorized && ev.tls.daysLeft > 14, value: ev.tls ? `${ev.tls.issuer || 'unknown issuer'}, ${ev.tls.daysLeft} days left${ev.tls.error ? ` (${ev.tls.error})` : ''}` : 'not examined', advice: 'Use a trusted CA with automatic renewal.' },
  ];
  const passed = rows.filter((r) => r.pass).length;
  const grade = passed >= 9 ? 'A' : passed >= 7 ? 'B' : passed >= 5 ? 'C' : passed >= 3 ? 'D' : 'F';
  return { grade, rows };
}

function short(s: string) {
  return s.length > 120 ? `${s.slice(0, 119)}…` : s;
}
